\set ON_ERROR_STOP on
-- Fresh database only. Execute as the provisioning owner, never as app_user.
-- Intentionally no DROP, IF NOT EXISTS, or automatic migration of existing data.
BEGIN;
CREATE TABLE public.users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(50) NOT NULL UNIQUE,
    email varchar(255) NOT NULL UNIQUE,
    password varchar(255) NOT NULL,
    role varchar(255) NOT NULL CHECK (role IN ('USER', 'ADMIN', 'MODERATOR')),
    enabled boolean NOT NULL,
    created_at timestamp(6), updated_at timestamp(6)
);
CREATE TABLE public.categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL,
    slug varchar(120) NOT NULL UNIQUE,
    description varchar(500),
    created_at timestamp(6), updated_at timestamp(6)
);
CREATE TABLE public.posts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(255) NOT NULL,
    slug varchar(200) NOT NULL UNIQUE,
    content text NOT NULL,
    summary varchar(500),
    status varchar(255) NOT NULL CHECK (status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED')),
    author_id bigint NOT NULL REFERENCES public.users(id),
    category_id bigint REFERENCES public.categories(id),
    created_at timestamp(6), updated_at timestamp(6)
);
CREATE TABLE public.comments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content text NOT NULL,
    post_id bigint NOT NULL REFERENCES public.posts(id),
    author_id bigint NOT NULL REFERENCES public.users(id),
    parent_id bigint REFERENCES public.comments(id),
    depth integer NOT NULL,
    deleted boolean NOT NULL,
    created_at timestamp(6), updated_at timestamp(6)
);
CREATE TABLE public.refresh_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token varchar(255) NOT NULL UNIQUE,
    user_id bigint NOT NULL UNIQUE REFERENCES public.users(id),
    expires_at timestamp(6) with time zone NOT NULL
);
CREATE TABLE public.secure_records (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content text NOT NULL,
    owner_id bigint NOT NULL REFERENCES public.users(id)
);
COMMIT;
